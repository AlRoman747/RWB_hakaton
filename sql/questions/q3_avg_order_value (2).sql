-- ============================================================================
-- Capibara Analytics / Блок А, вопрос 3
-- Средний чек заказа, среднее число строк и единиц товара на заказ
-- ============================================================================
-- НАЗНАЧЕНИЕ
--   Характеристика типичного заказа: сколько платит покупатель (чек),
--   из скольких строк состоит заказ и сколько единиц товара в нём.
--
-- ОПРЕДЕЛЕНИЯ МЕТРИК
--   Популяция заказов: 'delivered' (семантика выручки из Q1).
--   Чек заказа: SUM(price + freight_value) по всем позициям заказа —
--   это полная сумма, которую покупатель заплатил за заказ, включая
--   доставку. Чек — свойство ЗАКАЗА, поэтому сначала агрегируем позиции
--   в заказ, и только потом усредняем.
--   Среднее число строк: AVG(количество строк order_items в заказе).
--   Среднее число единиц: одна строка order_items = одна единица товара,
--   поэтому совпадает со средним числом строк; метрика приведена для
--   контроля уровня агрегации (см. tasks.md).
--
-- ЗАЩИТА ОТ ОШИБОК
--   - Двухшаговая агрегация: order_items → заказ → среднее по заказам.
--     Усреднение по строкам позиций дало бы «среднюю строку», а не
--     «средний чек» — это задокументированная ловушка.
--
-- ОЖИДАЕМАЯ СТРУКТУРА РЕЗУЛЬТАТА
--   avg_check (numeric) | avg_lines (numeric) | avg_units (numeric)
--   Одна строка.
--
-- КОНТРОЛЬНЫЕ ПРОВЕРКИ (выполнены на исходных CSV)
--   1. avg_check = 159.88.
--   2. Типичные неверные ответы (контроль от обратного):
--      123.75 — средняя цена позиции без доставки;
--      139.97 — средняя позиция с доставкой. Оба означают смешение
--      уровня позиции с уровнем заказа.
--   3. avg_lines = 1.14 (≈ 110 197 позиций / 96 478 заказов).
--
-- ВОЗМОЖНЫЕ РАСХОЖДЕНИЯ
--   - Если чек считать как SUM(price) без доставки, получится 137.04 —
--     это средняя товарная стоимость заказа, а не чек покупателя.
-- ============================================================================

WITH order_totals AS (                   -- уровень: заказ
    SELECT o.order_id,
           SUM(oi.price::numeric + oi.freight_value::numeric) AS check_amount,
           COUNT(*) AS lines_count
    FROM raw.orders o
    JOIN raw.order_items oi
      ON oi.order_id = o.order_id
    WHERE o.order_status = 'delivered'
    GROUP BY o.order_id
)
SELECT ROUND(AVG(check_amount), 2) AS avg_check,
       ROUND(AVG(lines_count), 2) AS avg_lines,
       ROUND(AVG(lines_count), 2) AS avg_units   -- 1 строка = 1 единица товара
FROM order_totals;
