-- ============================================================================
-- Capibara Analytics / Блок А, вопрос 4
-- Покупатели и повторные покупки
-- ============================================================================
-- НАЗНАЧЕНИЕ
--   База покупателей: сколько уникальных людей покупало, сколько из них
--   вернулись за вторым заказом, и доля вернувшихся.
--
-- ОПРЕДЕЛЕНИЯ МЕТРИК
--   Стабильный ключ покупателя: raw.customers.customer_unique_id.
--   В таблице customers два идентификатора:
--     - customer_id — технический ключ, который система выдаёт на КАЖДЫЙ
--       заказ заново (один customer_unique_id ↔ много customer_id);
--     - customer_unique_id — устойчивый идентификатор человека между
--       заказами. Только он подходит для анализа возвратов.
--   Популяция заказов: ВСЕ заказы (любой статус). Покупатель остаётся
--   покупателем, даже если его заказ отменили или товара не оказалось:
--   вопрос про базу клиентов, а не про выручку, поэтому фильтр
--   по статусу здесь неприменим (с delivered получилось бы 93 358).
--   Вернувшийся покупатель: customer_unique_id с ≥ 2 заказами.
--   Доля: вернувшиеся / все покупатели × 100.
--
-- ЗАЩИТА ОТ ОШИБОК
--   - Сначала COUNT заказов на уровне customer_unique_id, затем сводные
--     метрики — один человек считается ровно один раз независимо от
--     числа заказов и позиций в них.
--   - JOIN orders↔customers по customer_id: customers содержит по строке
--     на customer_id (99 441 = числу заказов), умножения нет.
--
-- ОЖИДАЕМАЯ СТРУКТУРА РЕЗУЛЬТАТА
--   total_customers (bigint) | returning_customers (bigint)
--   | returning_share_pct (numeric)
--   Одна строка.
--
-- КОНТРОЛЬНЫЕ ПРОВЕРКИ (выполнены на исходных CSV)
--   1. total_customers = 96 096.
--   2. returning_share_pct = 3.12 (2 997 вернувшихся).
--   3. Контроль от обратного: customer_id вместо customer_unique_id даёт
--      99 441 «покупателей» и 0% возвратов — признак неверного ключа.
--
-- ВОЗМОЖНЫЕ РАСХОЖДЕНИЯ
--   - Фильтр по delivered занижает базу до 93 358 и долю до 3.00%:
--     отменённые заказы — тоже факт покупки клиентом.
-- ============================================================================

WITH orders_per_customer AS (            -- уровень: покупатель (unique_id)
    SELECT c.customer_unique_id,
           COUNT(*) AS orders_count
    FROM raw.customers c
    JOIN raw.orders o
      ON o.customer_id = c.customer_id
    GROUP BY c.customer_unique_id
)
SELECT COUNT(*)                                          AS total_customers,
       COUNT(*) FILTER (WHERE orders_count > 1)          AS returning_customers,
       ROUND(
           COUNT(*) FILTER (WHERE orders_count > 1) * 100.0 / COUNT(*),
           2
       )                                                 AS returning_share_pct
FROM orders_per_customer;
