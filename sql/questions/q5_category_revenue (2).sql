-- ============================================================================
-- Capibara Analytics / Блок А, вопрос 5
-- Выручка по категориям товаров и доля в общей выручке
-- ============================================================================
-- НАЗНАЧЕНИЕ
--   Структура выручки по товарным категориям (португальские названия
--   из raw.products) с долей каждой категории в общей выручке.
--
-- ОПРЕДЕЛЕНИЯ МЕТРИК
--   Популяция заказов и выручка: как в Q1 — 'delivered', SUM(price).
--   Категория: raw.products.product_category_name. Товары с пустой
--   категорией НЕ исключаются — это осознанное решение: исключение
--   теряло бы ~2.5% выручки безвозвратно и ломало сверку с итогом.
--   Такие позиции собираются в явный бакет '(no category)'.
--   Доля: revenue категории / общая выручка × 100. Общая выручка
--   считается той же агрегацией (оконная сумма), а не константой —
--   контрольное значение в вычислениях не используется.
--
-- ЗАЩИТА ОТ ОШИБОК
--   - JOIN order_items → products по product_id: products — справочник
--     1:1 к product_id, умножения строк нет; LEFT JOIN сохраняет позиции
--     без карточки товара (таких нет, но запрос от этого защищён).
--   - Окно SUM() OVER () считает итог без второго прохода и без
--     самосоединения.
--   - Детерминированная сортировка: revenue DESC, category ASC.
--
-- ОЖИДАЕМАЯ СТРУКТУРА РЕЗУЛЬТАТА
--   category (text) | revenue (numeric) | revenue_share_pct (numeric)
--   74 строки: 73 заполненные категории + '(no category)'.
--
-- КОНТРОЛЬНЫЕ ПРОВЕРКИ (выполнены на исходных CSV)
--   1. COUNT(*) = 74 категории.
--   2. Крупнейшая категория (beleza_saude) — 1 233 131.72.
--   3. SUM(revenue) по всем строкам = 13 221 498.11 — сходится
--      с общей выручкой из Q1 (главная сверка отчёта).
--   4. SUM(revenue_share_pct) ≈ 100.00 (±0.01 из-за округления).
--
-- ВОЗМОЖНЫЕ РАСХОЖДЕНИЯ
--   - INNER JOIN к products отбрасывает позиции без категории →
--     итог меньше 13 221 498.11 и 73 строки вместо 74.
--   - Перевод категорий через product_category_name_translation меняет
--     только подписи; в справочнике 71 строка, часть категорий останется
--     без перевода — на суммы это не влияет.
-- ============================================================================

WITH category_revenue AS (               -- уровень: товарная позиция → категория
    SELECT COALESCE(NULLIF(p.product_category_name, ''), '(no category)') AS category,
           SUM(oi.price::numeric) AS revenue
    FROM raw.order_items oi
    JOIN raw.orders o
      ON o.order_id = oi.order_id
     AND o.order_status = 'delivered'
    LEFT JOIN raw.products p
      ON p.product_id = oi.product_id
    GROUP BY 1
)
SELECT category,
       revenue,
       ROUND(revenue * 100.0 / SUM(revenue) OVER (), 2) AS revenue_share_pct
FROM category_revenue
ORDER BY revenue DESC, category ASC;
